# LoopMaxPro - generates include/lmp_version.h from the VERSION file.
# The header is rewritten only when its content changes, to avoid useless rebuilds.
import os
import subprocess
from datetime import datetime, timezone

Import("env")  # noqa: F821  (provided by PlatformIO)

project_dir = env.subst("$PROJECT_DIR")  # noqa: F821
version_file = os.path.join(project_dir, "VERSION")
header_file = os.path.join(project_dir, "include", "lmp_version.h")


def read_version():
    try:
        with open(version_file, "r", encoding="utf-8") as f:
            return f.read().strip() or "0.0.0"
    except OSError:
        return "0.0.0"


def git_hash():
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=project_dir, capture_output=True, text=True, timeout=5)
        return out.stdout.strip() if out.returncode == 0 else ""
    except (OSError, subprocess.SubprocessError):
        return ""


version = read_version()
commit = git_hash()
# Build date has day resolution: the header changes at most once a day.
build_date = datetime.now(timezone.utc).strftime("%Y-%m-%d")
full = version + ("+" + commit if commit else "")

content = (
    "// Generated by tools/pio/version.py - do not edit.\n"
    "#pragma once\n"
    '#define LMP_VERSION "%s"\n'
    '#define LMP_VERSION_FULL "%s"\n'
    '#define LMP_BUILD_DATE "%s"\n'
) % (version, full, build_date)

previous = None
if os.path.exists(header_file):
    with open(header_file, "r", encoding="utf-8") as f:
        previous = f.read()

if previous != content:
    os.makedirs(os.path.dirname(header_file), exist_ok=True)
    with open(header_file, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    print("LoopMaxPro version %s (%s)" % (full, build_date))
